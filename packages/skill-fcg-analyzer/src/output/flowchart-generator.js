const fs = require('fs');
const path = require('path');

/**
 * Generate a human-readable flowchart report.
 * Produces:
 * - Mermaid diagram source (.flow.mmd)
 * - Markdown report with diagram, summaries, and bounded previews (.flow.md)
 *
 * @param {Object} fcgJson
 * @param {Object} options
 * @returns {{mermaid: string, markdown: string}}
 */
function generateFlowchartArtifacts(fcgJson, options = {}) {
  const mermaid = generateMermaid(fcgJson);
  const markdown = generateMarkdownReport(fcgJson, mermaid, options);
  return { mermaid, markdown };
}

/**
 * Save flowchart report files.
 *
 * @param {Object} fcgJson
 * @param {string} markdownPath
 * @param {string} mermaidPath
 */
function saveFlowchartArtifacts(fcgJson, markdownPath, mermaidPath) {
  const mdResolved = path.resolve(markdownPath);
  const mmdResolved = path.resolve(mermaidPath);
  const mdDir = path.dirname(mdResolved);
  const mmdDir = path.dirname(mmdResolved);

  if (!fs.existsSync(mdDir)) {
    fs.mkdirSync(mdDir, { recursive: true });
  }
  if (!fs.existsSync(mmdDir)) {
    fs.mkdirSync(mmdDir, { recursive: true });
  }

  const artifacts = generateFlowchartArtifacts(fcgJson);
  fs.writeFileSync(mdResolved, artifacts.markdown, 'utf-8');
  fs.writeFileSync(mmdResolved, artifacts.mermaid, 'utf-8');
  console.log(`Flowchart report saved to: ${mdResolved}`);
  console.log(`Mermaid graph saved to: ${mmdResolved}`);
}

function generateMermaid(fcgJson) {
  const lines = [];
  lines.push('flowchart TD');
  lines.push('  %% Auto-generated by Skill FCG Analyzer');

  for (const node of fcgJson.nodes || []) {
    const label = buildNodeLabel(node);
    lines.push(`  ${node.id}["${escapeMermaid(label)}"]`);
  }

  for (const edge of fcgJson.edges || []) {
    const edgeLabel = buildEdgeLabel(edge);
    const arrow = edge.is_feedback_edge ? '-.->' : edgeArrow(edge.type);
    lines.push(`  ${edge.source} ${arrow}|${escapeMermaid(edgeLabel)}| ${edge.target}`);
  }

  lines.push('');
  lines.push('  %% Node classes');
  lines.push('  classDef source fill:#D8F3DC,stroke:#1B4332,color:#081C15,stroke-width:1px;');
  lines.push('  classDef sink fill:#FFE5D9,stroke:#9D0208,color:#370617,stroke-width:1px;');
  lines.push('  classDef critical fill:#FFD6A5,stroke:#6A040F,color:#370617,stroke-width:2px;');
  lines.push('  classDef intermediate fill:#E5E5E5,stroke:#6C757D,color:#212529,stroke-width:1px;');

  for (const node of fcgJson.nodes || []) {
    if (node.is_critical) {
      lines.push(`  class ${node.id} critical;`);
    } else if (node.category === 'Source') {
      lines.push(`  class ${node.id} source;`);
    } else if (node.category === 'Sink') {
      lines.push(`  class ${node.id} sink;`);
    } else {
      lines.push(`  class ${node.id} intermediate;`);
    }
  }

  return lines.join('\n');
}

function generateMarkdownReport(fcgJson, mermaid, options = {}) {
  const generatedAt = new Date().toISOString();
  const topPathCount = Number(options.topPathCount || 30);
  const topClusterCount = Number(options.topClusterCount || 20);

  const lines = [];
  lines.push('# FCG Human-Readable Flowchart');
  lines.push('');
  lines.push(`- Skill: **${safe(fcgJson.meta?.skill_name)}**`);
  lines.push(`- Version: **${safe(fcgJson.meta?.skill_version)}**`);
  lines.push(`- Analysis Mode: **${safe(fcgJson.meta?.analysis_mode)}**`);
  lines.push(`- Generated At: **${generatedAt}**`);
  lines.push(`- Analyzer Timestamp: **${safe(fcgJson.meta?.analysis_timestamp)}**`);
  lines.push('');
  lines.push('## Diagram (Mermaid)');
  lines.push('');
  lines.push('```mermaid');
  lines.push(mermaid);
  lines.push('```');
  lines.push('');
  lines.push('## Statistics');
  lines.push('');
  lines.push('```json');
  lines.push(JSON.stringify(fcgJson.statistics || {}, null, 2));
  lines.push('```');
  lines.push('');
  lines.push('## Path Compression Summary');
  lines.push('');
  const compression = fcgJson.paths?.path_compression || {};
  lines.push('- Exact Source->Sink path count: ' + safe(compression.exact_path_count ?? fcgJson.paths?.source_to_sink_path_count_exact ?? 0));
  lines.push('- Compression nodes: ' + Number((compression.compression_nodes || []).length));
  lines.push('- Compression edges: ' + Number((compression.compression_edges || []).length));
  lines.push('- Source/Sink pairs: ' + Number((compression.source_sink_pairs || []).length));
  lines.push('');
  lines.push('| source | sink | path_count | representative_length |');
  lines.push('| --- | --- | ---: | ---: |');
  for (const pair of (compression.source_sink_pairs || []).slice(0, 20)) {
    lines.push(
      `| ${escapePipe(pair.source_node || '')} | ${escapePipe(pair.sink_node || '')} | ${Number(pair.path_count || 0)} | ${Number((pair.representative_path_nodes || []).length)} |`
    );
  }
  if (!(compression.source_sink_pairs || []).length) {
    lines.push('| - | - | 0 | 0 |');
  }
  lines.push('');
  lines.push('## Path Clusters (Semantic Groups)');
  lines.push('');
  lines.push('| cluster_id | path_count | representative_path | template | risk_distribution | documents | triggers | policies |');
  lines.push('| --- | ---: | --- | --- | --- | --- | --- | --- |');

  const pathClusters = (fcgJson.paths?.path_clusters || []).slice(0, topClusterCount);
  for (const cluster of pathClusters) {
    lines.push(
      `| ${safe(cluster.cluster_id)} | ${Number(cluster.path_count || 0)} | ${safe(cluster.representative_path_id)} | ${escapePipe(cluster.semantic_template || '')} | ${escapePipe(formatRiskDistribution(cluster.risk_distribution))} | ${escapePipe(summarizeList(cluster.involved_documents))} | ${escapePipe(summarizeList(cluster.involved_triggers))} | ${escapePipe(summarizeList(cluster.involved_policies))} |`
    );
  }

  if (pathClusters.length === 0) {
    lines.push('| - | 0 | - | - | - | - | - | - |');
  }
  lines.push('');
  lines.push('## Formal Markdown Semantics');
  lines.push('');
  lines.push('| node | file | line | operation | targets | conditions | effects | evidence |');
  lines.push('| --- | --- | ---: | --- | --- | --- | --- | --- |');

  const semanticNodes = (fcgJson.nodes || [])
    .filter(node => node.formal_semantics)
    .sort((a, b) => {
      const fileA = String(a.location?.file || '');
      const fileB = String(b.location?.file || '');
      if (fileA !== fileB) return fileA.localeCompare(fileB);
      return Number(a.location?.line || 0) - Number(b.location?.line || 0);
    });

  for (const node of semanticNodes) {
    const semantics = node.formal_semantics || {};
    lines.push(
      `| ${escapePipe(node.name || node.id || '')} | ${escapePipe(node.location?.file || '')} | ${Number(node.location?.line || 0)} | ${escapePipe(semantics.operation_type || '')} | ${escapePipe(formatSemanticTargets(semantics.targets))} | ${escapePipe(formatSemanticConditions(semantics.conditions))} | ${escapePipe(summarizeList(semantics.effects, 4))} | ${escapePipe(semantics.evidence?.text || '')} |`
    );
  }

  if (semanticNodes.length === 0) {
    lines.push('| - | - | 0 | - | - | - | - | - |');
  }
  lines.push('');
  lines.push('## Top Source->Sink Paths');
  lines.push('');
  lines.push('| path_id | source | sink | length | risk | data_transferred |');
  lines.push('| --- | --- | --- | ---: | --- | --- |');

  const nodeMap = new Map((fcgJson.nodes || []).map(node => [node.id, node]));
  const topPaths = (fcgJson.paths?.source_to_sink_paths || []).slice(0, topPathCount);
  for (const pathItem of topPaths) {
    const sourceName = nodeMap.get(pathItem.source_node)?.name || pathItem.source_node || '';
    const sinkName = nodeMap.get(pathItem.sink_node)?.name || pathItem.sink_node || '';
    lines.push(
      `| ${safe(pathItem.path_id)} | ${escapePipe(sourceName)} | ${escapePipe(sinkName)} | ${pathItem.length || 0} | ${safe(pathItem.risk_level)} | ${escapePipe(pathItem.data_transferred || '')} |`
    );
  }

  if (topPaths.length === 0) {
    lines.push('| - | - | - | 0 | - | - |');
  }
  lines.push('');
  lines.push('## Security Transfer Analysis');
  lines.push('');
  const security = fcgJson.security_profile || {};
  lines.push(`- Security Profile Version: ${safe(security.version || '')}`);
  lines.push(`- Node Profiles: ${Number((security.node_profiles || []).length)}`);
  lines.push(`- Doc Step Nodes: ${Number(security.statistics?.doc_step_node_count || 0)}`);
  lines.push(`- Legacy Doc Operation Nodes: ${Number(security.statistics?.doc_operation_node_count || 0)}`);
  lines.push(`- Label Flows: ${Number((security.label_flows || []).length)}`);
  lines.push(`- Provenance Edges: ${Number((security.provenance_graph?.propagation_edges || []).length)}`);
  lines.push(`- Observations: ${Number((security.observations || []).length)}`);
  lines.push(`- Truncated: ${Boolean(security.statistics?.truncated)}`);
  lines.push('');
  lines.push('### Observations');
  lines.push('');
  lines.push('| observation_id | label_flows | node | roles | labels | origins | boundary |');
  lines.push('| --- | --- | --- | --- | --- | --- | --- |');
  const labelFlowMap = new Map((security.label_flows || []).map(flow => [flow.label_flow_id, flow]));
  for (const observation of (security.observations || []).slice(0, 30)) {
    const flows = (observation.label_flow_ids || []).map(id => labelFlowMap.get(id)).filter(Boolean);
    lines.push(
      `| ${safe(observation.observation_id)} | ${escapePipe(summarizeList(observation.label_flow_ids || [], 4))} | ${escapePipe(observation.node_name || observation.node_id || '')} | ${escapePipe(summarizeList(observation.node_roles, 4))} | ${escapePipe(summarizeList(flows.map(flow => flow.label?.label), 4))} | ${escapePipe(summarizeList(flows.map(flow => flow.origin_node_name || flow.origin_node), 3))} | ${escapePipe(formatBoundary(observation.boundary))} |`
    );
  }
  if (!(security.observations || []).length) {
    lines.push('| - | - | - | - | - | - | - |');
  }
  lines.push('');
  lines.push('## Detail Preview');
  lines.push('');
  lines.push('### Nodes');
  lines.push('');
  lines.push('```json');
  lines.push(JSON.stringify((fcgJson.nodes || []).slice(0, 80), null, 2));
  lines.push('```');
  lines.push('');
  lines.push('### Edges');
  lines.push('');
  lines.push('```json');
  lines.push(JSON.stringify((fcgJson.edges || []).slice(0, 120), null, 2));
  lines.push('```');
  lines.push('');
  lines.push('### Source/Sink');
  lines.push('');
  lines.push('```json');
  lines.push(JSON.stringify(fcgJson.source_sink || {}, null, 2));
  lines.push('```');
  lines.push('');
  lines.push('### Paths');
  lines.push('');
  lines.push('```json');
  lines.push(JSON.stringify(previewPaths(fcgJson.paths || {}), null, 2));
  lines.push('```');
  lines.push('');
  lines.push('### Risks');
  lines.push('');
  lines.push('```json');
  lines.push(JSON.stringify((fcgJson.risks || []).slice(0, 80), null, 2));
  lines.push('```');
  lines.push('');
  lines.push('### Security Profile');
  lines.push('');
  lines.push('```json');
  lines.push(JSON.stringify(previewSecurityProfile(fcgJson.security_profile || {}), null, 2));
  lines.push('```');
  lines.push('');

  return lines.join('\n');
}

function previewPaths(paths = {}) {
  return {
    all_paths: (paths.all_paths || []).slice(0, 60),
    source_to_sink_paths: (paths.source_to_sink_paths || []).slice(0, 60),
    path_clusters: (paths.path_clusters || []).slice(0, 40),
    source_to_sink_path_count_exact: paths.source_to_sink_path_count_exact,
    path_compression: {
      ...(paths.path_compression || {}),
      compression_nodes: (paths.path_compression?.compression_nodes || []).slice(0, 80),
      compression_edges: (paths.path_compression?.compression_edges || []).slice(0, 120),
      source_sink_pairs: (paths.path_compression?.source_sink_pairs || []).slice(0, 80)
    }
  };
}

function previewSecurityProfile(security = {}) {
  const provenance = security.provenance_graph || {};
  const events = provenance.events || {};
  return {
    version: security.version || '',
    node_profiles: (security.node_profiles || []).slice(0, 40),
    label_flows: (security.label_flows || []).slice(0, 80),
    node_flow_sets: (security.node_flow_sets || []).slice(0, 40),
    provenance_graph: {
      graph_id: provenance.graph_id || '',
      label_flow_nodes: (provenance.label_flow_nodes || []).slice(0, 80),
      propagation_edges: (provenance.propagation_edges || []).slice(0, 120),
      observation_links: (provenance.observation_links || []).slice(0, 120),
      events: {
        routing: (events.routing || []).slice(0, 80),
        filtering: (events.filtering || []).slice(0, 80),
        merge: (events.merge || []).slice(0, 60),
        observation: (events.observation || []).slice(0, 80),
        truncation: (events.truncation || []).slice(0, 80)
      },
      statistics: provenance.statistics || {}
    },
    observations: (security.observations || []).slice(0, 80),
    statistics: security.statistics || {}
  };
}

function buildNodeLabel(node) {
  const parts = [
    node.id,
    node.name
  ];
  if (node.category) parts.push(`category=${node.category}`);
  if (node.type) parts.push(`type=${node.type}`);
  if (node.is_critical) parts.push('critical=true');
  return parts.join('\\n');
}

function buildEdgeLabel(edge) {
  const pieces = [edge.id || '', edge.type || 'data_dependency'];
  if (edge.is_feedback_edge) {
    pieces.unshift('feedback');
    if (edge.feedback_plausibility) pieces.push(edge.feedback_plausibility);
  }
  if (typeof edge.confidence === 'number') {
    pieces.push(`conf=${edge.confidence.toFixed(2)}`);
  }
  if (edge.data_flow?.from_param || edge.data_flow?.to_param) {
    pieces.push(`${edge.data_flow?.from_param || '?'}->${edge.data_flow?.to_param || '?'}`);
  }
  return pieces.filter(Boolean).join(' | ');
}

function edgeArrow(type) {
  if (type === 'doc_instruction') return '-.->';
  if (type === 'control_flow') return '==>';
  if (type === 'semantic') return '-->';
  return '-->';
}

function escapeMermaid(value) {
  return String(value || '')
    .replace(/"/g, '\\"')
    .replace(/\|/g, '/')
    .replace(/\r/g, '')
    .replace(/\n/g, '\\n');
}

function escapePipe(value) {
  return safe(value).replace(/\|/g, '\\|');
}

function safe(value) {
  return String(value ?? '');
}

function summarizeList(values, limit = 2) {
  const list = Array.isArray(values) ? values : [];
  if (list.length === 0) return '-';
  if (list.length <= limit) return list.join(', ');
  return `${list.slice(0, limit).join(', ')} ... (+${list.length - limit})`;
}

function formatRiskDistribution(distribution = {}) {
  const critical = Number(distribution.critical || 0);
  const high = Number(distribution.high || 0);
  const medium = Number(distribution.medium || 0);
  const low = Number(distribution.low || 0);
  return `critical=${critical}, high=${high}, medium=${medium}, low=${low}`;
}

function formatSemanticTargets(targets) {
  const list = Array.isArray(targets) ? targets : [];
  if (list.length === 0) return '-';
  return summarizeList(list.map(target => `${target.type}:${target.value}`), 4);
}

function formatSemanticConditions(conditions) {
  const list = Array.isArray(conditions) ? conditions : [];
  if (list.length === 0) return '-';
  return summarizeList(list.map(condition => `${condition.type}:${condition.text}`), 3);
}

function formatBoundary(boundary = {}) {
  return [
    boundary.data_surface,
    boundary.receiver_scope,
    boundary.retention_scope,
    boundary.trust_boundary
  ].filter(Boolean).join(' / ') || '-';
}

function deriveFlowchartPaths(jsonOutputPath, customFlowchartPath = '') {
  if (customFlowchartPath) {
    const mdPath = path.resolve(customFlowchartPath);
    const mmdPath = mdPath.replace(/\.md$/i, '.mmd');
    return {
      markdownPath: mdPath,
      mermaidPath: mmdPath === mdPath ? `${mdPath}.mmd` : mmdPath
    };
  }

  const resolvedJson = path.resolve(jsonOutputPath);
  const markdownPath = resolvedJson.replace(/\.json$/i, '.flow.md');
  const mermaidPath = resolvedJson.replace(/\.json$/i, '.flow.mmd');
  return { markdownPath, mermaidPath };
}

module.exports = {
  generateFlowchartArtifacts,
  saveFlowchartArtifacts,
  deriveFlowchartPaths
};
