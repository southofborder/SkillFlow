import {createRequire} from 'node:module';
import fs from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
const runtime=path.join(process.env.USERPROFILE,'.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules');
const require=createRequire(path.join(runtime,'placeholder.cjs'));
const {chromium}=require('playwright');
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',args:['--disable-gpu']});
const page=await browser.newPage({viewport:{width:1560,height:980},deviceScaleFactor:1});
const errors=[],external=[],dialogs=[];
page.on('pageerror',error=>errors.push(String(error)));
page.on('dialog',async d=>{dialogs.push(d.message());await d.dismiss()});
await page.route('**/*',route=>{const u=route.request().url();if(!u.startsWith('file:')){external.push(u);return route.abort()}return route.continue()});
const root=path.resolve('tmp/review-site-browser');
await page.goto(pathToFileURL(path.join(root,'review/index.html')).href);
await page.waitForSelector('svg [data-ir-id]');
if(await page.locator('.case').count()!==3)throw Error('case count');
await page.screenshot({path:path.join(root,'overview.png'),fullPage:true});
await page.locator('.case').filter({hasText:'002'}).click();
if(!await page.locator('#graph-empty').isVisible())throw Error('missing graph should show failure');
await page.selectOption('#feedback-filter','unresolved');
if(await page.locator('.case').count()!==1)throw Error('feedback filter');
await page.locator('.case').click();
if(!await page.locator('#case-header').innerText().then(t=>t.includes('003')))throw Error('case selection');
await page.selectOption('#feedback-filter','all');
await page.selectOption('#annotation-filter','incomplete');
if(await page.locator('.case').count()!==1)throw Error('annotation filter');
await page.locator('.case').click();
await page.selectOption('#annotation-filter','all');
await page.fill('#search','002');
if(await page.locator('.case').count()!==1)throw Error('text search');
await page.fill('#search','');
await page.locator('svg [data-ir-id]').click();
if(!await page.locator('#detail-panel').innerText().then(t=>t.includes('ir<&>"')&&t.includes('model_observe · 模型观察')&&t.includes('原文依据')))throw Error('operation evidence panel');
await page.screenshot({path:path.join(root,'operation.png'),fullPage:true});
const before=await page.locator('#zoom-value').innerText();
await page.click('#zoom-in');
if(await page.locator('#zoom-value').innerText()===before)throw Error('zoom');
const vp=await page.locator('#viewport').boundingBox();
const oldTransform=await page.locator('#graph-stage').getAttribute('style');
await page.mouse.move(vp.x+20,vp.y+20);await page.mouse.down();await page.mouse.move(vp.x+95,vp.y+55);await page.mouse.up();
if(await page.locator('#graph-stage').getAttribute('style')===oldTransform)throw Error('pan');
await page.getByRole('button',{name:'定位完整源文',exact:true}).click();
if(await page.locator('.source-line').count()!==3)throw Error('full source line count');
if(await page.locator('#detail-panel img').count())throw Error('source HTML executed');
if(!await page.locator('#detail-panel').innerText().then(t=>t.includes('</script><img src=x onerror=alert(1)>')))throw Error('source not preserved');
await page.screenshot({path:path.join(root,'source.png'),fullPage:true});
await page.getByRole('tab',{name:'语义核对'}).click();
await page.getByLabel('显示全部核对项（含保留与背景）').check();
if(await page.locator('.finding').count()!==1)throw Error('findings');
if(!await page.locator('#detail-panel').innerText().then(t=>t.includes('助手复核')&&t.includes('背景')))throw Error('review separation');
await page.screenshot({path:path.join(root,'audit.png'),fullPage:true});
if(errors.length||external.length||dialogs.length)throw Error(JSON.stringify({errors,external,dialogs}));
await fs.writeFile(path.join(root,'verification.json'),JSON.stringify({status:'passed',viewport:{width:1560,height:980},cases:3,checks:['three-column layout','case selection','feedback filter','annotation filter','text search','actual IR selection','Chinese labels','profile evidence','zoom','pan','complete source line index','literal malicious source not executed','audit records','assistant review separate'],page_errors:errors,external_requests:external,dialogs},null,2));
console.log('All offline Edge interactions passed.');
await browser.close();
